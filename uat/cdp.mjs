/**
 * Minimal Chrome DevTools Protocol client.
 *
 * No dependency: Node 22+ ships a global `WebSocket` and `fetch`, and this
 * needs three CDP methods. Pulling in `chrome-remote-interface` to send three
 * message types is not worth the dependency.
 *
 * ## Two targets, deliberately
 *
 *   RENDERER (--remote-debugging-port)  the real UI. Controls located by the
 *       text a human reads on them; inputs set the way React observes. This
 *       exercises the same path a person does, not a backdoor.
 *
 *   MAIN (--inspect)  globalThis.<HOOKS_GLOBAL>. Reaches what has no DOM:
 *       internal event logs, tray labels, window visibility.
 *
 * Anything reachable through the real UI goes through the RENDERER. The main
 * hooks are for state the UI cannot show, never a shortcut around a control
 * that exists on screen.
 *
 * Do not edit this file when adopting the scaffold. Edit config.mjs.
 */

const CONNECT_TIMEOUT_MS = 15_000;
const EVAL_TIMEOUT_MS = 15_000;

/** Poll an inspector's /json/list until a target matching `predicate` appears. */
async function discover(port, predicate, label) {
  const deadline = Date.now() + CONNECT_TIMEOUT_MS;
  let lastSeen = '(nothing)';
  while (Date.now() < deadline) {
    try {
      const res = await fetch(`http://127.0.0.1:${port}/json/list`);
      const targets = await res.json();
      lastSeen = targets.map((t) => `${t.type}:${t.title ?? t.url ?? ''}`).join(', ') || '(empty)';
      const hit = targets.find(predicate);
      if (hit?.webSocketDebuggerUrl) return hit;
    } catch {
      // inspector not up yet
    }
    await new Promise((r) => setTimeout(r, 250));
  }
  throw new Error(`CDP: no ${label} target on port ${port} within ${CONNECT_TIMEOUT_MS}ms. Saw: ${lastSeen}`);
}

export class CdpSession {
  constructor(ws, label) {
    this.ws = ws;
    this.label = label;
    this.nextId = 1;
    this.pending = new Map();
    ws.addEventListener('message', (ev) => {
      let msg;
      try {
        msg = JSON.parse(ev.data);
      } catch {
        return;
      }
      const p = this.pending.get(msg.id);
      if (!p) return;
      this.pending.delete(msg.id);
      clearTimeout(p.timer);
      p.resolve(msg);
    });
  }

  send(method, params = {}) {
    const id = this.nextId++;
    return new Promise((resolve, reject) => {
      const timer = setTimeout(() => {
        this.pending.delete(id);
        reject(new Error(`CDP[${this.label}]: ${method} timed out after ${EVAL_TIMEOUT_MS}ms`));
      }, EVAL_TIMEOUT_MS);
      this.pending.set(id, { resolve, timer });
      this.ws.send(JSON.stringify({ id, method, params }));
    });
  }

  /**
   * Evaluate an expression in the target and return its value.
   *
   * `awaitPromise` is on because most of what a harness asks for is async.
   * Remote exceptions are re-thrown on THIS side with the description
   * attached — a harness that swallows a remote throw reports a false pass,
   * which is the exact failure the self-test exists to rule out.
   */
  async evaluate(expression) {
    const res = await this.send('Runtime.evaluate', {
      expression,
      awaitPromise: true,
      returnByValue: true,
      allowUnsafeEvalBlockedByCSP: true,
    });
    const r = res.result;
    if (r?.exceptionDetails) {
      const d = r.exceptionDetails;
      throw new Error(`CDP[${this.label}] remote exception: ${d.exception?.description ?? d.text ?? 'unknown'}`);
    }
    if (res.error) throw new Error(`CDP[${this.label}] protocol error: ${JSON.stringify(res.error)}`);
    return r?.result?.value;
  }

  close() {
    try {
      this.ws.close();
    } catch {
      /* already gone */
    }
  }
}

async function open(url, label) {
  const ws = new WebSocket(url);
  await new Promise((resolve, reject) => {
    const t = setTimeout(() => reject(new Error(`CDP[${label}]: websocket open timed out`)), CONNECT_TIMEOUT_MS);
    ws.addEventListener('open', () => {
      clearTimeout(t);
      resolve();
    });
    ws.addEventListener('error', (e) => {
      clearTimeout(t);
      reject(new Error(`CDP[${label}]: websocket error ${e?.message ?? ''}`));
    });
  });
  const s = new CdpSession(ws, label);
  await s.send('Runtime.enable');
  return s;
}

/** Attach to the renderer — the page showing the UI. */
export async function attachRenderer(port) {
  const t = await discover(port, (x) => x.type === 'page', 'renderer/page');
  return open(t.webSocketDebuggerUrl, 'renderer');
}

/** Attach to the Electron main process — where the test hooks live. */
export async function attachMain(port) {
  const t = await discover(port, (x) => x.type === 'node' || x.type === 'javascript', 'main/node');
  return open(t.webSocketDebuggerUrl, 'main');
}
